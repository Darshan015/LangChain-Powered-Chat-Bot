from dotenv import load_dotenv
from langchain_google_genai import ChatGoogleGenerativeAI
#from langchassistantn_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
import os
import streamlit as st

load_dotenv()
llm = ChatGoogleGenerativeAI(model ="gemini-3.6-flash" )
parser = StrOutputParser()
st.title("🤖Di-Chat")
st.markdown("Your one step solution for all your queries✅")

if "messages" not in st.session_state:
    st.session_state.messages = []

for message in st.session_state.messages:
    role = message["role"]
    content = message["content"]
    st.chat_message(role).markdown(content)

query = st.chat_input("Shoot anything😶‍🌫️?")

if query:
    st.session_state.messages.append({"role":"user","content":query})
    st.chat_message("user").markdown(query)
    st.spinner("Wait a sec bro📌")
    res = llm.invoke(query)
    st.chat_message("ai").markdown(parser.invoke(res))
    st.session_state.messages.append({"role":"ai", "content":res.content})













































































































































































































































































































































